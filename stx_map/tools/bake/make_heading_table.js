// Writes ../../src/heading_table.inc: the quarter wave of the decoder's
// heading table, round(cos(2 pi k / 4096) * 16384) for k = 0 .. 1024, the
// same values turtle.js and tmap_decode.js compute. It checks that the C++
// decoder's quarter-wave reconstruction (cosine_at, sine_at in decode.cpp)
// gives turtle.js's COS and SIN for all 4096 headings, and that no entry
// lies near a rounding boundary, so the table does not depend on the libm
// that ran this script.
//
// usage: node make_heading_table.js
"use strict";
const fs = require("fs");
const path = require("path");
const T = require("./turtle.js");

const QUARTER = 1024;
const MARGIN = 1e-6;

function main() {
    const quarter = new Int32Array(QUARTER + 1);
    for (let k = 0; k <= QUARTER; k++) {
        const exact = Math.cos(2 * Math.PI * k / T.FINE) * 16384;
        const fraction = exact - Math.floor(exact);
        if (Math.abs(fraction - 0.5) < MARGIN) throw new Error("entry " + k + " lies on a rounding boundary");
        quarter[k] = Math.round(exact);
    }
    function cosineAt(heading) {
        const k = heading & (T.FINE - 1);
        if (k <= 1024) return quarter[k];
        if (k <= 2048) return -quarter[2048 - k];
        if (k <= 3072) return -quarter[k - 2048];
        return quarter[4096 - k];
    }
    for (let k = 0; k < T.FINE; k++) {
        if (cosineAt(k) !== T.COS[k]) throw new Error("cosine " + k + " differs");
        if (cosineAt(k + T.FINE - 1024) !== T.SIN[k]) throw new Error("sine " + k + " differs");
    }
    const lines = [
        "// Generated by tools/bake/make_heading_table.js; do not edit.",
        "// round(cos(2 pi k / 4096) * 16384) for k = 0 .. 1024 (a quarter wave).",
        "constexpr std::array<std::int16_t, 1025> quarter_cosine{"
    ];
    for (let k = 0; k <= QUARTER; k += 12) {
        const row = [];
        for (let j = k; j < Math.min(k + 12, QUARTER + 1); j++) row.push(String(quarter[j]));
        lines.push("    " + row.join(", ") + ",");
    }
    lines.push("};");
    fs.writeFileSync(path.join(__dirname, "..", "..", "src", "heading_table.inc"), lines.join("\n") + "\n");
}

main();
