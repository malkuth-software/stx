// Writes ../../src/world_map_data.inc from ../../data/world_map.tmap: the
// file's bytes as a constexpr array, which embedded.cpp returns as
// embedded_world_map().
//
// usage: node embed_map.js
"use strict";
const fs = require("fs");
const path = require("path");
const { decodeTmap } = require("./tmap_decode.js");

const PER_ROW = 20;

function main() {
    const root = path.join(__dirname, "..", "..");
    const bytes = new Uint8Array(fs.readFileSync(path.join(root, "data", "world_map.tmap")));
    decodeTmap(bytes); // refuses anything that is not a valid TMAP 2 file
    const lines = [
        "// Generated by tools/bake/embed_map.js from data/world_map.tmap; do not edit.",
        "constexpr std::array<unsigned char, " + bytes.length + "> world_map_bytes{"
    ];
    for (let at = 0; at < bytes.length; at += PER_ROW) {
        const row = [];
        for (let j = at; j < Math.min(at + PER_ROW, bytes.length); j++) row.push(String(bytes[j]));
        lines.push("    " + row.join(",") + ",");
    }
    lines.push("};");
    fs.writeFileSync(path.join(root, "src", "world_map_data.inc"), lines.join("\n") + "\n");
}

main();
